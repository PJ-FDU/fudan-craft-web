test('chat derives identity and team recipients from authority, rejects invalid messages and rate limits separately',()=>{
  const output:{side:Side;message:CommsMessage}[]=[];
  const room=new RoomComms((side,message)=>output.push({side,message}));
  room.update([{side:1,name:'A',team:1,connected:true},{side:2,name:'B',team:1,connected:true},{side:3,name:'C',team:3,connected:true},{side:4,name:'D',team:1,connected:false}]);
  output.length=0;
  room.receive(1,{type:'chat',text:'队友消息',channel:'team',side:3,name:'spoof'},1000);
  assert.deepEqual(output.map(o=>o.side),[1,2]);
  assert.equal((output[0].message as any).name,'A');assert.equal((output[0].message as any).side,1);
  output.length=0;room.receive(3,{type:'chat',text:'public <img onerror=x>',channel:'all'},1001);
  assert.deepEqual(output.map(o=>o.side),[1,2,3]);
  const id=(output[0].message as any).id;
  output.length=0;
  for(const text of ['', 'x'.repeat(301),42])room.receive(1,{type:'chat',text,channel:'team'},1002);
  room.receive(4,{type:'chat',text:'offline',channel:'all'},1002);
  assert.equal(output.filter(o=>o.message.type==='chat').length,0);
  for(let i=0;i<5;i++)room.receive(1,{type:'chat',text:'burst',channel:'team'},1003);
  assert.equal(output.filter(o=>o.message.type==='chat'&&o.side===2).length,4);
  assert.equal(output.at(-1)!.message.type,'comms-error');
  output.length=0;room.receive(1,{type:'chat',text:'later',channel:'all'},6001);
  assert.deepEqual(output.map(o=>o.side),[1,2,3]);
  assert.notEqual((output[0].message as any).id,id);
  const restarted=new RoomComms((side,message)=>output.push({side,message}));
  restarted.update([{side:1,name:'A',team:1,connected:true}]);output.length=0;
  restarted.receive(1,{type:'chat',text:'restart',channel:'all'},6002);
  assert.notEqual((output[0].message as any).id,id);
});
test('voice signals require two opted-in allies and both current sessions; disconnect and team changes revoke routes',()=>{
  const output:{side:Side;message:CommsMessage}[]=[];
  const room=new RoomComms((side,message)=>output.push({side,message}));
  const members=[{side:1 as const,name:'A',team:1,connected:true},{side:2 as const,name:'B',team:1,connected:true},{side:3 as const,name:'C',team:3,connected:true}];
  room.update(members);
  const a='a'.repeat(32),b='b'.repeat(32),c='c'.repeat(32);
  room.receive(1,{type:'voice-state',session:a});room.receive(2,{type:'voice-state',session:b});room.receive(3,{type:'voice-state',session:c});
  const opponents=output.filter(o=>o.side===3&&o.message.type==='voice-peers').at(-1)!.message as any;
  assert.deepEqual(opponents.peers.map((p:any)=>p.side),[3]);
  const signal={type:'voice-signal',to:2,session:a,targetSession:b,description:{type:'offer',sdp:'audio offer'}};
  output.length=0;room.receive(1,signal);assert.equal(output[0].side,2);
  assert.equal((output[0].message as any).from,1);
  output.length=0;
  room.receive(3,{...signal,session:c});room.receive(1,{...signal,targetSession:c});
  room.receive(1,{...signal,description:{type:'offer',sdp:'x'.repeat(12001)}});
  assert.equal(output.length,0);
  room.disconnect(2);output.length=0;room.receive(1,signal);assert.equal(output.length,0);
  room.receive(2,{type:'voice-state',session:c});output.length=0;room.receive(1,signal);assert.equal(output.length,0);
  room.receive(1,{...signal,targetSession:c});assert.equal(output.length,1);
  room.update(members.map(m=>m.side===2?{...m,team:2}:m));output.length=0;
  room.receive(1,{...signal,targetSession:c});assert.equal(output.length,0);
});
test('Pages room routes chat and voice through authenticated host seats and revokes a resumed microphone session',()=>{
  const output:{id:string;message:RoomMessage}[]=[],code='AABBCCDDEEFF:host';
  const room=new HostRoom(code,'host',(id,message)=>output.push({id,message}));
  room.connect('host');room.receive('host',{type:'create',mode:'coop',mapId:'lost-temple',name:'A'});
  room.connect('guest');room.receive('guest',{type:'join',code,name:'B'});
  const ticket=output.filter(o=>o.id==='guest'&&o.message.type==='lobby').at(-1)!.message;
  output.length=0;room.receive('guest',{type:'chat',channel:'team',text:'ready'});
  assert.deepEqual(output.filter(o=>o.message.type==='chat').map(o=>o.id),['host','guest']);
  room.receive('host',{type:'start'});assert.ok(room.engine);
  output.length=0;room.receive('guest',{type:'map-ping',kind:'attack',x:100,y:200});
  assert.deepEqual(output.filter(o=>o.message.type==='map-ping').map(o=>o.id),['host','guest']);
  output.length=0;room.receive('guest',{type:'quick-chat',quick:'resources',channel:'team'});
  assert.deepEqual(output.filter(o=>o.message.type==='chat').map(o=>o.id),['host','guest']);
  const a='a'.repeat(32),b='b'.repeat(32);
  room.receive('host',{type:'voice-state',session:a});room.receive('guest',{type:'voice-state',session:b});
  output.length=0;
  room.receive('host',{type:'voice-signal',to:2,session:a,targetSession:b,candidate:{candidate:'candidate',sdpMLineIndex:0}});
  assert.equal(output[0].id,'guest');
  room.disconnect('guest');room.connect('resumed');room.receive('resumed',{type:'resume',code,token:ticket.token});
  output.length=0;
  room.receive('host',{type:'voice-signal',to:2,session:a,targetSession:b,candidate:{candidate:'stale'}});
  assert.equal(output.length,0);
});
test('map pings validate battle bounds, route only to allies, and enforce a per-sender cooldown',()=>{
  const output:{side:Side;message:CommsMessage}[]=[];
  const room=new RoomComms((side,message)=>output.push({side,message}));
  const members=[{side:1 as const,name:'A',team:1,connected:true},{side:2 as const,name:'B',team:1,connected:true},{side:3 as const,name:'Enemy',team:3,connected:true}];
  room.update(members);output.length=0;
  room.receive(1,{type:'map-ping',kind:'attack',x:100,y:200},1000);
  assert.equal(output[0].message.type,'comms-error','lobby has no battle map');
  room.update(members,1000);output.length=0;
  for(const coordinates of [{x:NaN,y:1},{x:1,y:Infinity},{x:-1,y:1},{x:1001,y:1}])room.receive(1,{type:'map-ping',kind:'attack',...coordinates},1000);
  room.receive(1,{type:'map-ping',kind:'__proto__',x:1,y:1},1000);
  assert.equal(output.filter(o=>o.message.type==='map-ping').length,0);
  output.length=0;room.receive(1,{type:'map-ping',kind:'support',x:100,y:200,side:3,name:'spoof'},1000);
  assert.deepEqual(output.map(o=>o.side),[1,2]);assert.equal((output[0].message as any).name,'A');
  output.length=0;room.receive(1,{type:'map-ping',kind:'danger',x:100,y:200},2999);
  assert.equal(output[0].message.type,'comms-error');
  output.length=0;room.receive(2,{type:'map-ping',kind:'rally',x:1000,y:0},2000);
  assert.deepEqual(output.map(o=>o.side),[1,2]);
  output.length=0;room.receive(1,{type:'map-ping',kind:'attack',x:100,y:200},3000);
  assert.deepEqual(output.map(o=>o.side),[1,2]);
});
test('quick messages share text rate limits and are routed from server-owned presets',()=>{
  const output:{side:Side;message:CommsMessage}[]=[];
  const room=new RoomComms((side,message)=>output.push({side,message}));
  room.update([{side:1,name:'A',team:1,connected:true},{side:2,name:'Enemy',team:2,connected:true}]);output.length=0;
  room.receive(1,{type:'quick-chat',channel:'team',quick:'defend',text:'spoof'},1000);
  assert.deepEqual(output.map(o=>o.side),[1]);
  assert.equal((output[0].message as any).text,'请防守基地');
  output.length=0;room.receive(1,{type:'quick-chat',channel:'all',quick:'ready'},1000);
  assert.deepEqual(output.map(o=>o.side),[1,2]);
  for(let i=0;i<3;i++)room.receive(1,{type:'chat',channel:'all',text:'burst'},1000);
  output.length=0;room.receive(1,{type:'quick-chat',channel:'all',quick:'thanks'},1000);
  assert.equal(output[0].message.type,'comms-error');
  output.length=0;room.receive(1,{type:'quick-chat',channel:'all',quick:'constructor'},6000);
  assert.equal(output[0].message.type,'comms-error');
});
