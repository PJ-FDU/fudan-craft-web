"""Inspect RGBA silhouettes and export crop/anchor metadata; never modifies images.

Run after replacing generated sheets: python3 scripts/index-animation-atlases.py
Requires Pillow for development only. Runtime/build use the committed TS metadata.
"""
from pathlib import Path
from PIL import Image
import json

ROOT = Path(__file__).resolve().parents[1]
UNITS = ['worker','soldier','scout','medic','sniper','tank','artillery','fighter','mech']
LAYOUTS = {**{f'animation-{k}': (8,10) for k in UNITS},
           'trees': (6,4), 'building-construction': (4,9),
           'building-damage': (4,9), 'building-production': (4,9), 'effects': (6,4)}
result = {}
for name, (columns, rows) in LAYOUTS.items():
    filename = name if name.startswith('animation-') else 'animation-'+name
    im = Image.open(ROOT/'public/assets/generated'/f'{filename}-v4.png').convert('RGBA')
    width,height=im.size
    alpha=im.getchannel('A'); values=list(alpha.getdata())
    occupancy=[sum(v>120 for v in values[y*width:(y+1)*width]) for y in range(height)]
    boundaries=[0]
    for row in range(1,rows):
        ideal=height*row/rows; reach=height/rows*.44
        candidates=range(max(boundaries[-1]+1,int(ideal-reach)),min(height,int(ideal+reach)))
        # Select a real transparent gutter near the nominal split, rather than cutting a foot.
        cut=min(candidates,key=lambda y:occupancy[y]+abs(y-ideal)*.002)
        boundaries.append(cut)
    boundaries.append(height)
    frames=[]
    for row in range(rows):
        top,bottom=boundaries[row:row+2]
        column_occupancy=[sum(values[y*width+x]>120 for y in range(top,bottom)) for x in range(width)]
        cuts=[0]
        for col in range(1,columns):
            ideal=width*col/columns;reach=width/columns*.44
            candidates=range(max(cuts[-1]+1,int(ideal-reach)),min(width,int(ideal+reach)))
            cuts.append(min(candidates,key=lambda x:column_occupancy[x]+abs(x-ideal)*.002))
        cuts.append(width)
        for col in range(columns):
            left,right=cuts[col:col+2]
            occupied=[]; solid_rows=[]
            for y in range(top,bottom):
                strong=0
                for x in range(left,right):
                    a=values[y*width+x]
                    if a>32: occupied.append((x,y))
                    if a>170: strong+=1
                if strong>=max(3,(right-left)*.025):solid_rows.append(y)
            if not occupied: raise ValueError(f'Empty frame {name} {row}:{col}')
            x0=max(left,min(p[0] for p in occupied)-2);x1=min(right,max(p[0] for p in occupied)+3)
            y0=max(top,min(p[1] for p in occupied)-2);y1=min(bottom,max(p[1] for p in occupied)+3)
            # Atlas column center stays fixed; feet/wheels/foundation rest on the same world point.
            baseline=(solid_rows[-1]+1) if solid_rows else y1
            frames.append([x0,y0,x1-x0,y1-y0,round((left+right)/2-x0,2),baseline-y0])
    result[name]={'width':width,'height':height,'columns':columns,'rows':rows,'frames':frames}
    print(f'{name}: {columns*rows} frames, {width}x{height}')

target=ROOT/'src/game/atlas-frames.ts'
target.write_text('// Generated by scripts/index-animation-atlases.py. Source rectangles and contact anchors; no image pixels changed.\n'
                  'export interface AtlasFrames {width:number;height:number;columns:number;rows:number;frames:number[][]}\n'
                  'export const ATLAS_FRAMES:Record<string,AtlasFrames>='+json.dumps(result,separators=(',',':'))+';\n')
